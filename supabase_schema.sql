-- RPC 1: Authoritative Server-Side Coupon Validation
CREATE OR REPLACE FUNCTION public.validate_coupon_code(
    coupon_code TEXT,
    subtotal_amount NUMERIC DEFAULT 0.00
)
RETURNS JSONB AS $$
DECLARE
    found_coupon RECORD;
    computed_discount NUMERIC(10, 2) := 0.00;
BEGIN
    SELECT * INTO found_coupon 
    FROM public.coupons 
    WHERE UPPER(code) = UPPER(TRIM(coupon_code))
      AND is_active = true
      AND (valid_until IS NULL OR valid_until > NOW());

    IF NOT FOUND THEN
        RETURN jsonb_build_object(
            'valid', false,
            'message', 'Invalid or expired promo code.'
        );
    END IF;

    IF subtotal_amount < found_coupon.min_order_amount THEN
        RETURN jsonb_build_object(
            'valid', false,
            'message', format('Minimum order amount of $%s required for this coupon.', found_coupon.min_order_amount)
        );
    END IF;

    IF found_coupon.discount_type = 'percentage' THEN
        computed_discount := ROUND((subtotal_amount * (found_coupon.discount_value / 100.0)), 2);
        IF found_coupon.max_discount IS NOT NULL AND computed_discount > found_coupon.max_discount THEN
            computed_discount := found_coupon.max_discount;
        END IF;
    ELSIF found_coupon.discount_type = 'fixed' THEN
        computed_discount := LEAST(found_coupon.discount_value, subtotal_amount);
    ELSIF found_coupon.discount_type = 'free_shipping' THEN
        computed_discount := 0.00;
    END IF;

    RETURN jsonb_build_object(
        'valid', true,
        'code', found_coupon.code,
        'discount_type', found_coupon.discount_type,
        'discount_value', found_coupon.discount_value,
        'discount_amount', computed_discount,
        'message', 'Promo code applied successfully.'
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- RPC 2: Atomic Server-Side Order Pricing & Placement
CREATE OR REPLACE FUNCTION public.create_authenticated_order(
    order_payload JSONB
)
RETURNS JSONB AS $$
DECLARE
    item_elem JSONB;
    p_id TEXT;
    p_qty INTEGER;
    db_product RECORD;
    computed_subtotal NUMERIC(10, 2) := 0.00;
    computed_discount NUMERIC(10, 2) := 0.00;
    computed_shipping NUMERIC(10, 2) := 0.00;
    computed_tax NUMERIC(10, 2) := 0.00;
    computed_total NUMERIC(10, 2) := 0.00;
    
    in_coupon_code TEXT;
    coupon_res JSONB;
    
    new_order_id TEXT;
    new_tracking_no TEXT;
    est_delivery DATE;
    verified_items JSONB := '[]'::jsonb;
BEGIN
    -- 1. Validate items and calculate subtotal authoritatively from DB prices
    FOR item_elem IN SELECT * FROM jsonb_array_elements(order_payload->'items')
    LOOP
        p_id := item_elem->>'id';
        p_qty := COALESCE((item_elem->>'quantity')::INTEGER, (item_elem->>'qty')::INTEGER, 1);
        
        -- Lookup product by id or fallback by name
        SELECT * INTO db_product FROM public.products WHERE id = p_id OR name = (item_elem->>'name') LIMIT 1;
        
        IF NOT FOUND THEN
            RAISE EXCEPTION 'Product not found in store catalog: %', COALESCE(p_id, item_elem->>'name');
        END IF;

        IF db_product.stock_quantity < p_qty THEN
            RAISE EXCEPTION 'Insufficient stock for % (Requested: %, Available: %)', db_product.name, p_qty, db_product.stock_quantity;
        END IF;

        computed_subtotal := computed_subtotal + (db_product.price * p_qty);

        -- Build verified item payload with DB authoritative price
        verified_items := verified_items || jsonb_build_object(
            'id', db_product.id,
            'name', db_product.name,
            'price', db_product.price,
            'quantity', p_qty,
            'size', COALESCE(item_elem->>'size', 'M'),
            'color', COALESCE(item_elem->>'color', 'Default'),
            'image', COALESCE(item_elem->>'image', (db_product.images->0->>'url'), 'images/product-01.jpg')
        );
    END LOOP;

    -- 2. Validate and apply coupon server-side
    in_coupon_code := TRIM(COALESCE(order_payload->>'coupon_code', ''));
    IF in_coupon_code <> '' THEN
        coupon_res := public.validate_coupon_code(in_coupon_code, computed_subtotal);
        IF (coupon_res->>'valid')::BOOLEAN THEN
            computed_discount := (coupon_res->>'discount_amount')::NUMERIC;
        END IF;
    END IF;

    -- 3. Calculate shipping & tax
    IF (order_payload->>'shipping_method') = 'Express Delivery' THEN
        computed_shipping := 15.00;
    ELSIF computed_subtotal >= 100.00 OR (coupon_res IS NOT NULL AND coupon_res->>'discount_type' = 'free_shipping') THEN
        computed_shipping := 0.00;
    ELSE
        computed_shipping := 9.99;
    END IF;

    computed_tax := 0.00;
    computed_total := GREATEST(0.00, computed_subtotal - computed_discount) + computed_shipping + computed_tax;

    -- 4. Generate order identifiers & estimated delivery
    new_order_id := 'ORD-' || FLOOR(100000 + RANDOM() * 900000)::TEXT;
    new_tracking_no := 'GS-TRK-' || FLOOR(10000000 + RANDOM() * 90000000)::TEXT;
    
    IF (order_payload->>'shipping_method') = 'Express Delivery' THEN
        est_delivery := CURRENT_DATE + INTERVAL '2 days';
    ELSE
        est_delivery := CURRENT_DATE + INTERVAL '4 days';
    END IF;

    -- 5. Insert order atomically into orders table
    INSERT INTO public.orders (
        order_id,
        user_id,
        customer_name,
        email,
        phone,
        shipping_address,
        shipping_method,
        payment_method,
        payment_status,
        order_status,
        tracking_number,
        estimated_delivery,
        items,
        subtotal,
        discount,
        shipping_fee,
        tax,
        total,
        notes
    ) VALUES (
        new_order_id,
        CASE WHEN (order_payload->>'user_id') IS NOT NULL AND (order_payload->>'user_id') ~ '^[0-9a-fA-F-]{36}$' THEN (order_payload->>'user_id')::UUID ELSE NULL END,
        COALESCE(order_payload->>'customer_name', 'Guest Customer'),
        COALESCE(order_payload->>'email', 'customer@ganeshstore.com'),
        order_payload->>'phone',
        COALESCE(order_payload->>'shipping_address', '123 Luxury Lane, New York, NY'),
        COALESCE(order_payload->>'shipping_method', 'Standard Delivery'),
        COALESCE(UPPER(order_payload->>'payment_method'), 'CARD'),
        'COMPLETED',
        'processing',
        new_tracking_no,
        est_delivery,
        verified_items,
        computed_subtotal,
        computed_discount,
        computed_shipping,
        computed_tax,
        computed_total,
        order_payload->>'notes'
    );

    RETURN jsonb_build_object(
        'success', true,
        'order_id', new_order_id,
        'tracking_number', new_tracking_no,
        'subtotal', computed_subtotal,
        'discount', computed_discount,
        'shipping_fee', computed_shipping,
        'tax', computed_tax,
        'total', computed_total,
        'estimated_delivery', to_char(est_delivery, 'Dy, Mon DD, YYYY')
    );
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


-- RPC 3: Encrypted 2FA Secret Storage & Verification Helpers
CREATE OR REPLACE FUNCTION public.enable_user_2fa(
    p_user_id UUID,
    p_secret_text TEXT,
    p_encryption_key TEXT DEFAULT 'ganeshstore_totp_secure_vault_key'
)
RETURNS JSONB AS $$
BEGIN
    UPDATE public.profiles
    SET two_factor_enabled = true,
        two_factor_secret = pgp_sym_encrypt(p_secret_text, p_encryption_key)::TEXT,
        updated_at = TIMEZONE('utc'::text, NOW())
    WHERE id = p_user_id;

    RETURN jsonb_build_object('success', true, 'message', '2FA enabled with pgcrypto encryption at rest.');
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;

CREATE OR REPLACE FUNCTION public.get_decrypted_2fa_secret(
    p_user_id UUID,
    p_encryption_key TEXT DEFAULT 'ganeshstore_totp_secure_vault_key'
)
RETURNS TEXT AS $$
DECLARE
    raw_val TEXT;
    decrypted TEXT;
BEGIN
    SELECT two_factor_secret INTO raw_val FROM public.profiles WHERE id = p_user_id;
    
    IF raw_val IS NULL THEN
        RETURN NULL;
    END IF;

    -- If secret was encrypted via pgp_sym_encrypt
    IF raw_val LIKE '\x%' OR raw_val LIKE '-----BEGIN PGP MESSAGE%' THEN
        BEGIN
            decrypted := pgp_sym_decrypt(raw_val::bytea, p_encryption_key);
            RETURN decrypted;
        EXCEPTION WHEN OTHERS THEN
            RETURN raw_val;
        END;
    END IF;

    RETURN raw_val;
END;
$$ LANGUAGE plpgsql SECURITY DEFINER;


